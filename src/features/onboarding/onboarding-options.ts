/* Auto-compute MSME category from investment + turnover values */
const TURNOVER_CRORE: Record<string, number> = {
  lt_20l: 0.2,
  '20l_40l': 0.4,
  '40l_1cr': 1,
  '1cr_5cr': 5,
  '5cr_25cr': 25,
  '25cr_50cr': 50,
  '50cr_250cr': 250,
  gt_250cr: 999,
};

const INVEST_CRORE: Record<string, number> = {
  lt_1cr: 1,
  '1cr_10cr': 10,
  '10cr_50cr': 50,
  gt_50cr: 999,
};

export const computeMsmeCategory = (investVal: string, turnoverVal: string): string => {
  const inv = INVEST_CRORE[investVal] ?? 0;
  const turn = TURNOVER_CRORE[turnoverVal] ?? 0;
  if (inv <= 1 && turn <= 5) return 'Micro Enterprise';
  if (inv <= 10 && turn <= 50) return 'Small Enterprise';
  if (inv <= 50 && turn <= 250) return 'Medium Enterprise';
  return 'Non-MSME';
};
